def safe(f):
    def g(x):
        try:
            return f(x)
        except ZeroDivisionError:
            return math.inf
        except (ValueError, OverflowError):
            return math.nan
    return g


def gen_quad():
    from fermium.interp import quad, _Fail
    w = Writer("quad.txt", """
v1's adaptive Gauss-Kronrod (fermium.interp.quad, which mirrors the compiled fm_quad), rtol 1e-10.
name  v1_value all_zero truth   |   name ERR kind a b truth   (truth: nan when v1's value is right)""")
    for name, f, a, b, truth in QUAD_CASES:
        t = math.nan if truth is None else truth
        zero = []
        try:
            v = quad(safe(f), a, b, warn=lambda: zero.append(1))
            w.row(name, v, 1.0 if zero else 0.0, t)
        except _Fail as fl:
            w.row(name, "ERR", str(fl.kind), fl.a, fl.b, t)
    w.close()


