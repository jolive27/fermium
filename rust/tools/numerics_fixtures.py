def _vdp(t, y):
    return [y[1], 5.0 * (1 - y[0] * y[0]) * y[1] - y[0]]


def _kepler(t, y):
    r3 = (y[0] * y[0] + y[1] * y[1]) ** 1.5
    return [y[2], y[3], -y[0] / r3, -y[1] / r3]


