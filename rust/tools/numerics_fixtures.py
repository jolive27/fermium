#!/usr/bin/env python3
"""Generate the reference fixtures for fermium-runtime's native numerics (spec §B6).

Python (Fermium 1.5 = the oracle, plus SciPy/NumPy where v1 called them) is used HERE ONLY, to write
plain-text fixtures under rust/crates/fermium-runtime/tests/fixtures/; `cargo test -p fermium-runtime`
compares the Rust results with them. Nothing at run time needs Python.

Format: one case per line, `name value value ...`, floats as Python repr (shortest round trip), or
`name ERR kind a b` for a v1 run-time error. Lines starting with # are comments.

Run from the repository root:  python3 rust/tools/numerics_fixtures.py [section ...]
"""
from __future__ import annotations

import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, "rust", "crates", "fermium-runtime", "tests", "fixtures")

inf = math.inf


def r(x):
    return repr(float(x))


class Writer:
    def __init__(self, name, header):
        self.path = os.path.join(OUT, name)
        self.lines = [f"# {line}" for line in header.strip().splitlines()]
        self.lines.append("# generated by rust/tools/numerics_fixtures.py; do not edit")

    def row(self, name, *vals):
        self.lines.append(" ".join([name] + [v if isinstance(v, str) else r(v) for v in vals]))

    def close(self):
        os.makedirs(OUT, exist_ok=True)
        with open(self.path, "w") as fh:
            fh.write("\n".join(self.lines) + "\n")
        print(f"wrote {os.path.relpath(self.path, ROOT)} ({len(self.lines)} lines)")


